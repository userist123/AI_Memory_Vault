// Phase 2 promise: the Visual System 02 re-themes (.home, .ws, .ws .side) now come from tokens.css and every
// custom property still computes to its original value inside each scope.
import test from 'node:test';
import assert from 'node:assert/strict';
import path from 'node:path';
import { ROOT, CASA3D_APP, read, rootProps, ruleProps, computed, normalize } from './lib.mjs';

const SCOPES = [['.home'], ['.ws'], ['.ws', '.ws .side']];
const fixture = read(path.join(ROOT, 'test/fixtures/casa3d-scopes-baseline.css'));
const rootBaseline = rootProps(read(path.join(ROOT, 'test/fixtures/casa3d-root-baseline.css')));
const tokensCss = read(path.join(CASA3D_APP, 'tokens.css'));
const globalsCss = read(path.join(CASA3D_APP, 'globals.css'));

const before = (sel) => [rootBaseline, ...sel.map((s) => ruleProps(fixture, s))];
const after = (sel) => [
  new Map([...rootProps(tokensCss), ...rootProps(globalsCss)]),
  ...sel.map((s) => new Map([...ruleProps(tokensCss, s), ...ruleProps(globalsCss, s)])),
];

test('scope fixture holds the three original blocks', () => {
  assert.deepEqual(['.home', '.ws', '.ws .side'].map((s) => ruleProps(fixture, s).size), [24, 24, 22]);
});

for (const sel of SCOPES) {
  const scope = sel.at(-1);
  test(`${scope}: every property computes to its original value`, () => {
    const names = new Set([...rootBaseline.keys(), ...before(sel).flatMap((m) => [...m.keys()])]);
    for (const name of names) {
      const want = computed(before(sel), name);
      const got = computed(after(sel), name);
      assert.notEqual(got, undefined, `${scope} ${name} is no longer defined`);
      assert.equal(normalize(got), normalize(want), `${scope} ${name}: ${got}, was ${want}`);
    }
  });

  test(`${scope}: generated by tokens.css, not written in globals.css`, () => {
    assert.ok(ruleProps(tokensCss, scope).size > 0, `tokens.css has no ${scope} block`);
    assert.deepEqual([...ruleProps(globalsCss, scope).keys()], [], `globals.css still declares them in ${scope}`);
  });
}

test('globals.css declares no property that tokens.css generates (except the coarse-pointer --hit)', () => {
  // Any such rule would silently beat or shadow the token source; re-themes belong in tokens/brands/*/scopes.
  const generated = new Set([...tokensCss.matchAll(/^\s*(--[a-z0-9-]+)\s*:/gim)].map((m) => m[1]));
  const css = globalsCss.replace(/\/\*[\s\S]*?\*\//g, '').replace(/@media\s*\(pointer:\s*coarse\)\s*\{\s*:root\s*\{\s*--hit:\s*44px;?\s*\}\s*\}/, '');
  const hits = [...css.matchAll(/(?:^|[;{\s])(--[a-z0-9-]+)\s*:/gim)].map((m) => m[1]).filter((n) => generated.has(n));
  assert.deepEqual([...new Set(hits)], []);
});
