// Builds one CSS file per brand from the DTCG sources (core + tokens/brands/<brand>) with Style Dictionary.
// `node build.mjs` writes dist/<brand>/tokens.css and every copyTo target named in brands/<brand>/brand.json.
// The tests import renderBrand() to check that the committed files equal a fresh build (drift gate).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import StyleDictionary from 'style-dictionary';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const TOKENS = path.join(ROOT, 'tokens');

const jsonFiles = (dir) =>
  fs.readdirSync(dir).filter((f) => f.endsWith('.json') && f !== 'brand.json').sort().map((f) => path.join(dir, f));

const px = (d) => (d.value === 0 ? '0' : `${d.value}${d.unit}`);

// Style Dictionary 5.6.0 recomputes colours from the components (rounding can move a channel by 1) and has no
// transform for the DTCG `duration` type (`time/seconds` only matches `time`), so these three are our own.
function cssColor(c) {
  if (!c || typeof c !== 'object' || !/^#[0-9A-Fa-f]{6}$/.test(c.hex ?? '')) {
    throw new Error(`expected a DTCG colour object with hex, got ${JSON.stringify(c)}`);
  }
  if (c.alpha === undefined || c.alpha === 1) return c.hex;
  const [r, g, b] = c.hex.slice(1).match(/../g).map((x) => parseInt(x, 16));
  return `rgb(${r} ${g} ${b} / ${c.alpha})`;
}

StyleDictionary.registerTransform({
  name: 'color/vault-css',
  type: 'value',
  filter: (t) => t.$type === 'color',
  transform: (t) => cssColor(t.$value),
});

StyleDictionary.registerTransform({
  name: 'duration/vault-css',
  type: 'value',
  filter: (t) => t.$type === 'duration',
  transform: (t) => `${t.$value.value}${t.$value.unit}`,
});

StyleDictionary.registerTransform({
  name: 'shadow/vault-css',
  type: 'value',
  transitive: true,
  filter: (t) => t.$type === 'shadow',
  transform: (t) =>
    [t.$value]
      .flat()
      .map((s) => {
        const spread = s.spread.value === 0 ? '' : ` ${px(s.spread)}`;
        return `${s.inset ? 'inset ' : ''}${px(s.offsetX)} ${px(s.offsetY)} ${px(s.blur)}${spread} ${cssColor(s.color)}`;
      })
      .join(', '),
});

const HEADER = (brand) => [
  `/* Generated by design-system/build.mjs from design-system/tokens (core + brands/${brand}). Do not edit:`,
  '   change the token JSON and run `npm run build` in design-system. */',
];

// `selector { --token: value; ... --old-name: var(--token); }` for the given tokens.
function cssBlock(selector, tokens, aliases, known, allNames) {
  const names = new Set(tokens.map((t) => t.name));
  const lines = tokens.map((t) => `  --${t.name}: ${t.$value};`);
  const alias = Object.entries(aliases ?? {}).flatMap(([old, target]) => {
    if (!known.has(target)) throw new Error(`alias --${old}: no token ${target}`);
    const name = target.replaceAll('.', '-');
    // `shadow-1` -> shadow.1 already has that name; writing it again would be `--x: var(--x)`, a cycle.
    if (old === name) return [];
    if (allNames.has(old)) throw new Error(`alias --${old} collides with token --${old}`);
    // var() is substituted where it is declared, so a scope repeats the alias of every token it re-themes.
    return names.has(name) ? [`  --${old}: var(--${name});`] : [];
  });
  return [`${selector} {`, ...lines, alias.length ? '  /* names the app already uses */' : null, ...alias, '}'].filter(
    (l) => l !== null,
  );
}

const readJson = (f) => JSON.parse(fs.readFileSync(f, 'utf8'));

// Later trees win; a token node (one with $value) is replaced whole, so a scope cannot inherit a stray alpha.
function merge(into, from) {
  for (const [k, v] of Object.entries(from)) {
    if (v && typeof v === 'object' && !Array.isArray(v) && !('$value' in v) && into[k] && typeof into[k] === 'object') {
      merge(into[k], v);
    } else {
      into[k] = structuredClone(v);
    }
  }
  return into;
}

function tokenPaths(tree, trail = [], out = new Set()) {
  if ('$value' in tree) return out.add(trail.join('.'));
  for (const [k, v] of Object.entries(tree)) if (!k.startsWith('$') && v && typeof v === 'object') tokenPaths(v, [...trail, k], out);
  return out;
}

async function resolveTokens(tree) {
  const sd = new StyleDictionary({
    tokens: tree,
    usesDtcg: true,
    log: { warnings: 'error', verbosity: 'silent' },
    platforms: {
      css: { transforms: ['name/kebab', 'color/vault-css', 'size/px', 'duration/vault-css', 'cubicBezier/css', 'fontFamily/css', 'shadow/vault-css'] },
    },
  });
  return (await sd.getPlatformTokens('css')).allTokens;
}

export function listBrands() {
  return fs
    .readdirSync(path.join(TOKENS, 'brands'), { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort();
}

export async function renderBrand(name) {
  const dir = path.join(TOKENS, 'brands', name);
  const brand = readJson(path.join(dir, 'brand.json'));
  const base = [...jsonFiles(path.join(TOKENS, 'core')), ...jsonFiles(dir)].reduce((t, f) => merge(t, readJson(f)), {});
  const rootTokens = await resolveTokens(base);
  const known = new Set(rootTokens.map((t) => t.path.join('.')));
  const allNames = new Set(rootTokens.map((t) => t.name));
  const out = [...HEADER(name), ...cssBlock(':root', rootTokens, brand.aliases, known, allNames)];

  // Each scope re-themes a selector: it emits the tokens its own files declare plus every token whose final value
  // differs from the parent's (references such as color.paper.default follow the canvas they point at).
  const scopes = new Map();
  const scopeDir = path.join(dir, 'scopes');
  const listed = new Set((brand.scopes ?? []).map((s) => s.name));
  const onDisk = fs.existsSync(scopeDir) ? fs.readdirSync(scopeDir, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name) : [];
  for (const d of onDisk) if (!listed.has(d)) throw new Error(`scopes/${d} is not listed in brands/${name}/brand.json`);
  for (const s of brand.scopes ?? []) {
    if (scopes.has(s.name)) throw new Error(`scope ${s.name} is listed twice`);
    if (typeof s.selector !== 'string' || !s.selector.trim()) throw new Error(`scope ${s.name}: no selector`);
    const parent = s.parent ? scopes.get(s.parent) : { tree: base, tokens: rootTokens };
    if (!parent) throw new Error(`scope ${s.name}: parent ${s.parent} must come first`);
    const files = jsonFiles(path.join(dir, 'scopes', s.name));
    if (!files.length) throw new Error(`scope ${s.name}: no token files`);
    const own = files.reduce((t, f) => merge(t, readJson(f)), {});
    const declared = tokenPaths(own);
    for (const p of declared) if (!known.has(p)) throw new Error(`scope ${s.name}: ${p} is not a ${name} token`);
    const tree = merge(structuredClone(parent.tree), own);
    const tokens = await resolveTokens(tree);
    const was = new Map(parent.tokens.map((t) => [t.name, t.$value]));
    const emit = tokens.filter((t) => declared.has(t.path.join('.')) || was.get(t.name) !== t.$value);
    scopes.set(s.name, { tree, tokens });
    out.push('', `/* scope ${s.name}: brands/${name}/scopes/${s.name} */`, ...cssBlock(s.selector, emit, brand.aliases, known, allNames));
  }
  const css = [...out, ''].join('\n');
  // dist/ is git-ignored (a local preview); the copyTo files are the committed outputs the drift test checks.
  const committed = (brand.copyTo ?? []).map((t) => path.resolve(ROOT, t));
  const targets = [path.join(ROOT, 'dist', name, 'tokens.css'), ...committed];
  return { css, targets, committed, brand };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  for (const name of listBrands()) {
    const { css, targets } = await renderBrand(name);
    for (const t of targets) {
      fs.mkdirSync(path.dirname(t), { recursive: true });
      fs.writeFileSync(t, css);
      console.log(`${name}: ${path.relative(ROOT, t)}`);
    }
  }
}
