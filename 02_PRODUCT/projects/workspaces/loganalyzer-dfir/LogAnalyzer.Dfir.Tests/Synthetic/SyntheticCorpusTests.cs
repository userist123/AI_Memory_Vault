    // ---- EVTX container ----------------------------------------------------------------------------------------------------------

    [Fact]
    public void Evtx_container_has_three_valid_chunks_with_consecutive_record_ids()
    {
        var p = P("evtx/container.evtx");
        Assert.Equal("evtx", EvidenceFingerprint.Detect(p));
        var chunks = EvtxRepair.Inspect(p);
        Assert.Equal(3, chunks.Count);
        Assert.All(chunks, c => Assert.True(c.Valid, c.Problem));
        Assert.Equal(1, chunks[0].FirstRecordId);
        Assert.Equal(30, chunks[2].LastRecordId);
    }

    [Fact]
    public void Evtx_damaged_chunk_is_found_dropped_and_the_record_gap_stays_visible()
    {
        var p = Path.Combine(_dir, "damaged.evtx");
        var b = SyntheticCorpus.EvtxContainer(3);
        b[4096 + 65536 + 512 + 100] ^= 0xFF;                               // flip a byte in chunk 1's record area
        File.WriteAllBytes(p, b);

        var bad = Assert.Single(EvtxRepair.Inspect(p), c => !c.Valid);
        Assert.Equal(1, bad.Index);
        Assert.Contains("CRC", bad.Problem);
        Assert.Equal((11, 20), (bad.FirstRecordId, bad.LastRecordId));

        var r = EvtxRepair.Repair(p, Path.Combine(_dir, "repaired.evtx"));
        Assert.Equal((3, 2), (r.TotalChunks, r.KeptChunks));
        var after = EvtxRepair.Inspect(r.OutputPath);
        Assert.All(after, c => Assert.True(c.Valid));
        Assert.Equal([1L, 21L], after.Select(c => c.FirstRecordId).ToArray());   // original IDs kept: the hole 11-20 is visible
        Assert.Equal(b, File.ReadAllBytes(p));                                    // the source file is never modified
    }

    [Fact]
    public void Evtx_non_evtx_input_is_rejected()
    {
        var f = Path.Combine(_dir, "x.evtx");
        File.WriteAllText(f, "not an event log");
        Assert.Throws<InvalidDataException>(() => EvtxRepair.Repair(f, Path.Combine(_dir, "y.evtx")));
    }
