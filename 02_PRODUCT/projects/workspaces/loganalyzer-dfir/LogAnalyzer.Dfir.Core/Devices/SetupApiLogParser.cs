using System.Globalization;
using System.Text.RegularExpressions;
using LogAnalyzer.Dfir.Model;
using LogAnalyzer.Dfir.Parsing;

namespace LogAnalyzer.Dfir.Devices;

/// <summary>
/// Windows' device installation log (<c>%SystemRoot%\INF\setupapi.dev.log</c>): one timeline row for every device Windows installed because the hardware
/// appeared („Device Install (Hardware initiated)”), with the device id, the serial when the id carries one, the section's start time and its exit status
/// (research 2026-11-07, plan P2.3: the file was collected but no parser read it). The times are LOCAL time of the station; they are converted with the time
/// zone recorded on the evidence item and the conversion is named on every row. Read as text only, bounded in size and line length.
/// </summary>
public sealed class SetupApiLogParser : EvidenceParserBase
{
    public const string SourceName = "SetupAPI";
    public const string SourceTypeName = "setupapi_log";
    public const long MaxLogBytes = 128L * 1024 * 1024;
    public const int MaxLineChars = 8192;

    public override ParserDescriptor Descriptor { get; } = new()
    {
        ParserId = "SetupApiLogParser", Version = "1.0", Artifact = "Jurnalul de instalare a dispozitivelor (setupapi.dev.log)",
        SourceTypes = [SourceTypeName], FileNames = ["setupapi.dev.log"], Fingerprints = ["setupapi_dev"],
        SupportedOs = "Windows 7 – Windows 11 (text scris de SetupAPI)",
        FormatVersions = ["secțiuni „>>>  [Device Install (Hardware initiated) - …]” / „>>>  Section start AAAA/LL/ZZ HH:MM:SS.mmm”"],
        MaxInputBytes = MaxLogBytes,
        Limitations =
        [
            "Arată prima instalare a unui dispozitiv pe stație, nu fiecare conectare: o reconectare a aceluiași dispozitiv nu mai apare.",
            "O reinstalare (după ștergerea driverului sau a dispozitivului din Device Manager) apare ca o nouă „primă” instalare.",
            "Fișierul se rotește când crește (setupapi.dev.AAAAMMZZ_HHMMSS.log); ce s-a rotit și a fost șters nu mai există.",
            "Ora este ora locală a stației; se convertește cu fusul orar înregistrat pe probă.",
            "Nu arată utilizatorul și nici ce fișiere s-au copiat.",
        ],
        Status = ParserMaturity.Tested,
        Validation = "SetupApiLogParserTests (secțiuni în formatul documentat de Microsoft, cu stick, telefon și instalări care nu sunt ale hardware-ului)",
    };

    private static readonly Regex Header = new(@"^>>>\s+\[Device Install \(Hardware initiated\) - (?<id>.+)\]\s*$", RegexOptions.CultureInvariant, TimeSpan.FromMilliseconds(200));
    private static readonly Regex Start = new(@"^>>>\s+Section start (?<t>\d{4}/\d{2}/\d{2} \d{2}:\d{2}:\d{2}(?:\.\d{1,3})?)", RegexOptions.CultureInvariant, TimeSpan.FromMilliseconds(200));
    private static readonly Regex Exit = new(@"^<<<\s+\[Exit status: (?<s>[^\]]+)\]", RegexOptions.CultureInvariant, TimeSpan.FromMilliseconds(200));
    private static readonly Regex UsbstorSerial = new(@"USBSTOR[\\#][^\\#]+[\\#](?<s>[^\\#&{]+)", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant, TimeSpan.FromMilliseconds(200));
    private static readonly Regex UsbSerial = new(@"^USB\\VID_(?<v>[0-9A-F]{4})&PID_(?<p>[0-9A-F]{4})(?:&MI_\d+)?\\(?<s>[^\\]+)$", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant, TimeSpan.FromMilliseconds(200));

    /// <summary>The serial an installed device id carries (USBSTOR or a USB device whose instance is not generated by Windows); "" otherwise. Pure.</summary>
    public static string SerialOf(string deviceId)
    {
        var id = deviceId.Trim();
        // review 2026-11-08: a stick with no serial gets an instance made by Windows („7&1a2b3c4d&0”): the "7" before the ampersand is not a serial
        if (UsbstorSerial.Match(id) is { Success: true } m)
        {
            var s = m.Groups["s"].Value;
            var rest = id[(m.Index + m.Length)..];
            return s.Length <= 2 && rest.StartsWith('&') ? "" : s;
        }
        // an instance like 6&1a2b3c&0&1 is made by Windows for a device with no serial; an ampersand marks it
        if (UsbSerial.Match(id) is { Success: true } u && !u.Groups["s"].Value.Contains('&')) return u.Groups["s"].Value;
        return "";
    }

    /// <summary>What the device id names, in plain words.</summary>
    public static string KindOf(string deviceId)
    {
        var id = deviceId.ToUpperInvariant();
        if (id.Contains("USBSTOR")) return "suport de stocare USB";
        if (id.StartsWith(@"SWD\WPDBUSENUM\", StringComparison.Ordinal)) return "volum sau dispozitiv portabil";
        if (id.StartsWith("BTHENUM", StringComparison.Ordinal) || id.StartsWith("BTHLE", StringComparison.Ordinal)) return "dispozitiv Bluetooth";
        if (id.StartsWith(@"USB\", StringComparison.Ordinal)) return "dispozitiv USB";
        if (id.StartsWith("SCSI\\", StringComparison.Ordinal) || id.StartsWith(@"STORAGE\", StringComparison.Ordinal)) return "disc";
        return "dispozitiv";
    }

    protected override void ParseCore(EvidenceItem item, string fullPath, IEventSink sink, ParseResult result, CancellationToken ct)
    {
        TimeZoneInfo zone;
        string zoneNote;
        try { zone = item.Timezone.Length > 0 ? TimeZoneInfo.FindSystemTimeZoneById(item.Timezone) : TimeZoneInfo.Utc; zoneNote = item.Timezone.Length > 0 ? item.Timezone : "UTC (fusul stației nu este pe probă)"; }
        catch (Exception ex) when (ex is TimeZoneNotFoundException or InvalidTimeZoneException) { zone = TimeZoneInfo.Utc; zoneNote = $"UTC (fusul „{item.Timezone}” nu este cunoscut)"; }

        using var fs = new FileStream(fullPath, FileMode.Open, FileAccess.Read, FileShare.ReadWrite | FileShare.Delete);
        using var sr = new StreamReader(fs, detectEncodingFromByteOrderMarks: true);
        string? device = null, started = null;
        long line = 0, headerLine = 0;
        void Flush(string exit)
        {
            if (device is null) return;
            Timestamp time;
            if (started is not null && DateTime.TryParseExact(started, ["yyyy/MM/dd HH:mm:ss.fff", "yyyy/MM/dd HH:mm:ss.ff", "yyyy/MM/dd HH:mm:ss.f", "yyyy/MM/dd HH:mm:ss"],
                    CultureInfo.InvariantCulture, DateTimeStyles.None, out var local))
                time = Timestamp.FromUtc(TimeZoneInfo.ConvertTimeToUtc(DateTime.SpecifyKind(local, DateTimeKind.Unspecified), zone), started, $"ora locală a stației ({zoneNote}) → UTC");
            else { time = Timestamp.Unknown(started ?? ""); result.MalformedRecords++; }
            var serial = SerialOf(device);
            var kind = KindOf(device);
            var e = new TimelineEvent
            {
                Time = time, Source = SourceName, EvidenceId = item.EvidenceId, Provider = "SetupAPI", EventId = "DeviceInstall",
                Summary = $"Prima instalare a unui {kind}: {device}{(exit.Length > 0 ? $" (rezultat: {exit})" : "")}",
                TimeSemantics = "device first installed (section start)", TemporalType = TemporalType.Historical,
                Classification = Classification.Direct, Confidence = Confidence.Medium, Locator = $"line={headerLine}", Path = "",
                Fields = { ["DeviceInstanceId"] = device, ["DeviceKind"] = kind, ["ExitStatus"] = exit },
            };
            if (serial.Length > 0) e.Fields["Serial"] = serial;
            sink.Add(e);
            result.Records++;
            device = null; started = null;
        }
        while (LogAnalyzer.Dfir.Network.FirewallLogParser.ReadBoundedLine(sr, MaxLineChars, out var tooLong) is { } l)
        {
            ct.ThrowIfCancellationRequested();
            line++;
            if (tooLong) { result.MalformedRecords++; continue; }
            if (!l.StartsWith(">>>", StringComparison.Ordinal) && !l.StartsWith("<<<", StringComparison.Ordinal)) continue;
            if (Header.Match(l) is { Success: true } h) { Flush(""); device = h.Groups["id"].Value.Trim(); headerLine = line; continue; }
            if (device is not null && started is null && Start.Match(l) is { Success: true } s) { started = s.Groups["t"].Value; continue; }
            if (device is not null && Exit.Match(l) is { Success: true } x) { Flush(x.Groups["s"].Value.Trim()); continue; }
            // another section starts before this one closed (a truncated or interleaved log): keep what was read
            if (device is not null && l.StartsWith(">>>  [", StringComparison.Ordinal)) Flush("");
        }
        Flush("");
    }
}
