"""B04: write (or check) the prompt-bias audit table of the Book-to-Memory harness.

    python 30_SCRIPTS/evaluation/b2m_prompt_audit.py            # (re)write 08_RESEARCH/BOOK_TO_MEMORY/PROMPT_AUDIT_B04.md
    python 30_SCRIPTS/evaluation/b2m_prompt_audit.py --check    # exit 1 if the committed file differs from the live prompts

The table is read from the live code (templates, default task text, context header) and from the frozen H1 case
set, so it cannot drift from the prompts it describes.
"""
from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "03_IMPLEMENTATION" / "packages"))
os.environ.setdefault("MEMORY_CONTROLLER_HMAC_SECRET", "0" * 32)

from lifecycle.validation.book_to_memory_prompt_audit import (  # noqa: E402
    LEADING_PATTERNS,
    audit_register,
    framing_variants,
    render_audit_markdown,
)

OUT = REPO / "08_RESEARCH" / "BOOK_TO_MEMORY" / "PROMPT_AUDIT_B04.md"


def render() -> str:
    patterns = "\n".join(f"| `{pid}` | {why} |" for pid, _rx, why in LEADING_PATTERNS)
    variants = framing_variants("<question>", "<note text>")
    return f"""# PROMPT_AUDIT_B04.md — prompt-bias audit of the Book-to-Memory harness

**Finding**: PR #209 B04, "task prompts have not been reviewed against counter-factual baselines".
**Generated by** `30_SCRIPTS/evaluation/b2m_prompt_audit.py` from the live code; `--check` (and
`20_TESTS/test_book_to_memory_prompt_audit.py`) fail if this file drifts from the prompts.

## Method

1. Every task prompt, prompt template and wrapper of the harness is listed in the register below with a verdict.
2. A set of known leading patterns (`LEADING_PATTERNS` in `book_to_memory_prompt_audit.py`) is applied to each
   prompt. The lint test fails on any prompt of the harness that carries one, and on any frozen H1 query that carries
   a flag not listed as by-design.
3. A prompt that led was rewritten neutrally. Frozen artifacts (the H1 case set, whose hash is bound into the experiment runner)
   are linted and reported but **not** rewritten, and the reason is stated per row.
4. Counterfactual variants (below) let a run show whether an effect survives a change of framing.

## Known leading patterns

| id | what is wrong with it |
|---|---|
{patterns}

## Register (verdict per prompt)

{render_audit_markdown(audit_register(REPO))}
## Counterfactual variants

`framing_variants(question, note_text)` returns the same reference material under two opposite framings:

* `neutral`: `{variants['neutral'].splitlines()[0]}` (a bare label);
* `reversed`: `{variants['reversed'].splitlines()[0]}`.

The B03 packet runs both (`WITH_NOTE`, `WITH_NOTE_SKEPTIC`) next to the baseline and a decoy-note control
(`WITH_DECOY_NOTE`), and the pre-registered analysis reports each contrast. For yes/no probes,
`reverse_polarity(statement_true, statement_false)` builds the two opposite-answer wordings of one fact, so a model that says
"yes" to both is visibly agreeing with the wording.

## What this audit does not show

* It finds the patterns it knows. A lint that passes is not a proof that a prompt is unbiased.
* The H1 `direct_lexical` queries repeat their target's words and the `multi_hop_associative` queries name the path; both are
  the conditions the H1 hypothesis is about, and they stay as frozen.
* No model has been run on any of these prompts yet (B03 is waiting on the owner); the framing contrast is prepared, not measured.
"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.name} differs from the live prompts; run without --check")
            return 1
        print("up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
