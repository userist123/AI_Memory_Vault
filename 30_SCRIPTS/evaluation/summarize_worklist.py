"""Summarise the real work-question run: relevance of what the memory returned, computed from the JSON.

Inputs (all under 07_EVALUATION/memory_usage/):
    work_session_results.json      what memory_search returned for each question (run_memory_worklist.py)
    work_session_judgements.json   a manual judgement of the first three results of each question

Every figure in the markdown is computed here. It also checks, from the storage engine, whether the
coordination file each question was taken from is a note the memory can return at all.

    python 30_SCRIPTS/evaluation/summarize_worklist.py [--out FILE.md]
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from collections import Counter
from pathlib import Path
from typing import Any, Dict, List

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "03_IMPLEMENTATION" / "packages"))
DIR = REPO / "07_EVALUATION" / "memory_usage"


def summarise(results: List[Dict[str, Any]], judgements: List[Dict[str, Any]], indexed_sources: Dict[str, bool]) -> Dict[str, Any]:
    judged = [m for j in judgements for m in j["judged"]]
    relevant = [m for m in judged if m["relevant"]]
    per_question = {j["question_id"]: sum(1 for m in j["judged"] if m["relevant"]) for j in judgements}
    returned = [row for r in results for row in r["returned"]]
    canonical = {"ACTIVE", "VERIFIED"}
    return {
        "questions": len(results),
        "questions_with_zero_results": sum(1 for r in results if not r["returned"]),
        "judged_results": len(judged),
        "relevant_results": len(relevant),
        "questions_with_a_relevant_top3": sum(1 for n in per_question.values() if n > 0),
        "returned_by_lifecycle": dict(Counter(str(row["lifecycle"]) for row in returned)),
        "returned_total": len(returned),
        "returned_not_active_or_verified": sum(1 for row in returned if row["lifecycle"] not in canonical),
        "returned_lowercase_or_missing_lifecycle": sorted({str(row["lifecycle"]) for row in returned
                                                           if row["lifecycle"] is None or row["lifecycle"] != str(row["lifecycle"]).upper()}),
        "distinct_notes_returned": len({row["id"] for row in returned}),
        "top1_shared_by_questions": Counter(r["returned"][0]["id"] for r in results if r["returned"]).most_common(3),
        "sources_indexed": sum(1 for v in indexed_sources.values() if v),
        "sources_total": len(indexed_sources),
    }


def indexed_sources(results: List[Dict[str, Any]]) -> Dict[str, bool]:
    os.environ.setdefault("MEMORY_CONTROLLER_HMAC_SECRET", "0" * 32)
    from memory_controller.storage.file_engine import FileStorageEngine
    engine = FileStorageEngine(str(REPO))
    paths = {Path(p).resolve() for p in engine.id_to_path.values()}
    return {src: (REPO / src).resolve() in paths for src in sorted({r["source_file"] for r in results})}


def render(s: Dict[str, Any]) -> str:
    lines = [
        "# Real work questions through the vault memory",
        "",
        "Generated by `30_SCRIPTS/evaluation/summarize_worklist.py` from `work_session_results.json` and",
        "`work_session_judgements.json`. The judgement of relevance is manual and single-evaluator (see the",
        "judgements file); everything else is computed. The sample is 20 questions: read it as an observation, not",
        "as a benchmark.",
        "",
        f"- Questions asked: {s['questions']}; with zero results: {s['questions_with_zero_results']}/{s['questions']}",
        f"- First three results judged relevant: {s['relevant_results']}/{s['judged_results']}",
        f"- Questions with at least one relevant result in the first three: {s['questions_with_a_relevant_top3']}/{s['questions']}",
        f"- Distinct notes returned: {s['distinct_notes_returned']} of {s['returned_total']} results",
        f"- Results that are not ACTIVE or VERIFIED: {s['returned_not_active_or_verified']}/{s['returned_total']}",
        f"- Coordination files behind the questions that the memory can return (they are indexed notes): "
        f"{s['sources_indexed']}/{s['sources_total']}",
        "",
        "## Lifecycle of the returned notes",
        "",
    ]
    lines += [f"- {name}: {n}/{s['returned_total']}" for name, n in sorted(s["returned_by_lifecycle"].items())]
    if s["returned_lowercase_or_missing_lifecycle"]:
        lines += ["", "Lifecycle values that are lower-case or missing (the RAW exclusion compares the exact string `RAW`): "
                  + ", ".join(f"`{v}`" for v in s["returned_lowercase_or_missing_lifecycle"]) + "."]
    lines += ["", "## Notes that are the first result for several questions", ""]
    lines += [f"- `{note_id}`: first result of {n} questions" for note_id, n in s["top1_shared_by_questions"]]
    lines.append("")
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--out", default=str(DIR / "WORKLIST_RELEVANCE.md"))
    args = parser.parse_args(argv)
    results = json.loads((DIR / "work_session_results.json").read_text(encoding="utf-8"))["results"]
    judgements = json.loads((DIR / "work_session_judgements.json").read_text(encoding="utf-8"))["judgements"]
    # Whether a coordination file was an indexed note is a fact about the vault on the day of the run;
    # it is recorded once so the summary can be recomputed later from the files alone.
    snapshot = DIR / "work_session_sources_indexed.json"
    if snapshot.exists():
        sources = json.loads(snapshot.read_text(encoding="utf-8"))
    else:
        sources = indexed_sources(results)
        snapshot.write_text(json.dumps(sources, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    text = render(summarise(results, judgements, sources))
    Path(args.out).write_text(text, encoding="utf-8", newline="\n")
    sys.stdout.reconfigure(encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
