def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def build(root: Path, upstream_repo: Path) -> tuple[dict, list[str]]:  # type: ignore[type-arg]
    errors: list[str] = []
    files = []
    for rel, up, reason in FILES:
        r = subprocess.run(["git", "-C", str(upstream_repo), "show", f"{COMMIT}:{up}"],  # noqa: S603,S607
                           capture_output=True, check=False)
        if r.returncode != 0:
            errors.append(f"{up}: not found at {COMMIT}")
            continue
        p = root / rel
        if not p.is_file():
            errors.append(f"{rel}: missing locally")
            continue
        up_sha, local_sha = _sha(r.stdout), _sha(p.read_bytes())
        patched = up_sha != local_sha
        if patched and not reason:
            errors.append(f"{rel}: differs from {COMMIT}:{up} but has no patch_reason in gen_vendored.py")
        if not patched and reason:
            errors.append(f"{rel}: identical to upstream but gen_vendored.py gives a patch_reason")
        files.append({"path": rel, "upstream_path": up, "upstream_commit": COMMIT, "upstream_sha256": up_sha,
                      "local_sha256": local_sha, "patched": patched, "patch_reason": reason if patched else ""})
    vendored_up = {up for _, up, _ in FILES}
    for up, _ in DROPPED_TESTS:
        if up.split("::")[0] in vendored_up and "::" not in up:
            errors.append(f"dropped_tests: {up} is vendored (stale entry)")
    manifest = {
        "upstream": "AI Website Studio",
        "upstream_commit": COMMIT,
        "note": NOTE,
        "files": files,
        "local_files": [{"path": p, "reason": r} for p, r in LOCAL_FILES],
        "dropped_tests": [{"upstream_path": p, "reason": r} for p, r in DROPPED_TESTS],
        "residuals": RESIDUALS,
    }
    return manifest, errors


def render(manifest: dict) -> bytes:  # type: ignore[type-arg]
    return (json.dumps(manifest, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", type=Path, default=ROOT)
    ap.add_argument("--upstream-repo", type=Path, required=True)
    ap.add_argument("--check", action="store_true", help="compare with the committed manifest, write nothing")
    args = ap.parse_args(argv)
    root = args.root.resolve()
    manifest, errors = build(root, args.upstream_repo)
    for e in errors:
        print(f"gen_vendored: {e}", file=sys.stderr)
    if errors:
        return 1
    data = render(manifest)
    target = root / MANIFEST
    if args.check:
        if not target.is_file() or target.read_bytes() != data:
            print(f"gen_vendored: {MANIFEST} is stale; rerun without --check", file=sys.stderr)
            return 1
        print(f"gen_vendored: {MANIFEST} up to date")
        return 0
    target.write_bytes(data)  # bytes: LF on every platform
    print(f"gen_vendored: wrote {MANIFEST} ({len(manifest['files'])} files)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
