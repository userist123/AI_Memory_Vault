def utc(): return datetime.now(timezone.utc).isoformat()
def sha(text): return hashlib.sha256(text.encode('utf-8')).hexdigest()

class OracleController:
    """Proxy that widens only the bounded page size for the diagnostic oracle."""
    def __init__(self, delegate): self.delegate = delegate
    def search(self, principal, query, page_size=5, **kwargs):
        return self.delegate.search(principal=principal, query=query, page_size=20, **kwargs)

def task_from(raw, test_code):
    return AgentTask(task_id=raw['task_id'], description=raw['prompt'], target_file='solution.py', test_file='test_task.py', instructions=raw['expected_behavior'], test_patch=test_code)

def mc_nemar(control, treatment):
    b=sum(1 for c,t in zip(control,treatment) if not c and t)
    c=sum(1 for x,y in zip(control,treatment) if x and not y)
    n=b+c
    if n == 0: return 1.0
    tail=sum(__import__('math').comb(n,k) for k in range(0,min(b,c)+1))
    return min(1.0, 2.0*tail/(2**n))

def main():
    if len(os.environ.get('MEMORY_CONTROLLER_HMAC_SECRET', '').strip()) < 32:
        raise SystemExit('MEMORY_CONTROLLER_HMAC_SECRET must be supplied via environment (>=32 characters)')
    tasks=json.loads((HERE/'golden_tasks.json').read_text(encoding='utf-8'))
    out=HERE/'runs_v2'
    traces=out/'traces'; workspaces=out/'workspaces'
    out.mkdir(exist_ok=True); traces.mkdir(exist_ok=True); workspaces.mkdir(exist_ok=True)
    # Check the real endpoint/model before starting the matrix.
    health=LocalProvider(model_name=MODEL).health()
    if health.get('status') != 'ok' or not health.get('model_available'):
        raise SystemExit('REAL_PROVIDER_FAILURE: ' + json.dumps(health, sort_keys=True))
    from cognitive_core.recall_cli import get_memory_controller
    controller=get_memory_controller()
    rows=[]; order_rng=random.Random(SEED)
    for repeat in range(1,4):
        for raw,test_code in zip(tasks,TESTS):
            order=CONDITIONS[:]; order_rng.shuffle(order)
            for condition in order:
                run_seed=SEED + repeat*100 + int(raw['task_id'][1:])
                workspace=workspaces/f"{raw['task_id']}_{repeat}_{condition.lower()}_{uuid.uuid4().hex[:8]}"
                workspace.mkdir(parents=True)
                # The verifier is part of the task environment and is identical
                # across conditions; solution.py must be generated by the model.
                (workspace/'test_task.py').write_text(test_code, encoding='utf-8')
                if condition == 'CONTROL':
                    harness=RealAgentExecutionHarness(memory_controller=controller, trace_dir=traces, model_executor=AgentModelExecutor(provider_mode='local', model_name=MODEL))
                    result, ref=harness.execute(task_from(raw,test_code), 'golden-agent', 'synthesizer', workspace, memory_query=None, enable_memory=False, verification_command=['python','-m','pytest','test_task.py','-q'])
                else:
                    ctrl=OracleController(controller) if condition=='FULL_CONTEXT_ORACLE' else controller
                    harness=RealAgentExecutionHarness(memory_controller=ctrl, trace_dir=traces, model_executor=AgentModelExecutor(provider_mode='local', model_name=MODEL))
                    result, ref=harness.execute(task_from(raw,test_code), 'golden-agent', 'synthesizer', workspace, memory_query=raw['prompt'], enable_memory=True, verification_command=['python','-m','pytest','test_task.py','-q'])
                record=ref['record']; trace_id=record['trace_id']
                record.update({'experiment_id':EXPERIMENT_ID,'run_id':f"{raw['task_id']}-{repeat}-{condition}",'condition':condition,'task_seed':SEED+int(raw['task_id'][1:]),'run_seed':run_seed,'condition_order':order,'git_commit':os.getenv('GIT_COMMIT','unknown'),'retrieval_enabled':condition!='CONTROL','provider':MODEL if record['model']['provider_name']=='local' else record['model']['provider_name'],'model_name':MODEL,'model_request_hash':sha(json.dumps(record['memory'],sort_keys=True)),'model_response_hash':sha(record['model'].get('response_text','')),'final_success':result['status']=='success'})
                enriched=traces/f"{trace_id}.benchmark.json"; enriched.write_text(json.dumps(record,indent=2),encoding='utf-8')
                rows.append({'task_id':raw['task_id'],'category':raw['category'],'repeat':repeat,'condition':condition,'run_id':record['run_id'],'trace_id':trace_id,'success':record['final_success'],'verification_status':record['verification']['status'],'verification_exit_code':record['verification']['exit_code'],'retrieval_count':record['memory']['retrieval_count'],'memory_ids':record['memory']['memory_ids'],'context_hash':record['memory']['context_hash'],'latency_ms':record['model']['latency_ms'],'files_created':record['workspace']['files_created'],'condition_order':order,'run_seed':run_seed})
                shutil.rmtree(workspace, ignore_errors=True)
    with (out/'execution_results.jsonl').open('w',encoding='utf-8') as f:
        for row in rows: f.write(json.dumps(row)+'\n')
    pairs=[]
    for repeat in range(1,4):
        for raw in tasks:
            subset={r['condition']:r for r in rows if r['task_id']==raw['task_id'] and r['repeat']==repeat}
            c,t,o=(subset[x] for x in CONDITIONS)
            delta=(1 if t['success'] and not c['success'] else -1 if c['success'] and not t['success'] else 0)
            pairs.append({'task_id':raw['task_id'],'repeat':repeat,'control':c,'treatment':t,'oracle':o,'classification':'HELPFUL' if delta==1 and t['memory_ids'] else 'HARMFUL' if delta==-1 and t['memory_ids'] else 'UNUSED' if not t['memory_ids'] else 'NEUTRAL'})
    with (out/'paired_results.jsonl').open('w',encoding='utf-8') as f:
        for row in pairs:f.write(json.dumps(row)+'\n')
    def rate(cond): return sum(r['success'] for r in rows if r['condition']==cond)
    total=len(tasks)*3
    c=[r['success'] for r in rows if r['condition']=='CONTROL']; t=[r['success'] for r in rows if r['condition']=='TREATMENT']; o=[r['success'] for r in rows if r['condition']=='FULL_CONTEXT_ORACLE']
    summary={'experiment_id':EXPERIMENT_ID,'provider':'local','model':MODEL,'tasks':len(tasks),'repeats':3,'executions':len(rows),'control_success':sum(c),'treatment_success':sum(t),'oracle_success':sum(o),'control_success_rate':sum(c)/total,'treatment_success_rate':sum(t)/total,'oracle_success_rate':sum(o)/total,'absolute_delta':sum(t)/total-sum(c)/total,'relative_delta':None if sum(c)==0 else (sum(t)-sum(c))/sum(c),'treatment_wins':sum(p['classification']=='HELPFUL' for p in pairs),'control_wins':sum(p['classification']=='HARMFUL' for p in pairs),'both_success':sum(p['control']['success'] and p['treatment']['success'] for p in pairs),'both_failure':sum(not p['control']['success'] and not p['treatment']['success'] for p in pairs),'mcnemar_p_value':mc_nemar(c,t),'oracle_gap_mean':sum(o[i]-t[i] for i in range(total))/total,'oracle_gap_median':median([o[i]-t[i] for i in range(total)]),'invalid_runs':sum(r['verification_status'] not in ('passed','failed') for r in rows)}
    (out/'effectiveness_summary.json').write_text(json.dumps(summary,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(summary,sort_keys=True))

if __name__=='__main__': main()
